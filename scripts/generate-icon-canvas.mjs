import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const antdRequire = createRequire(require.resolve('antd'));
const iconsRequire = createRequire(antdRequire.resolve('@ant-design/icons'));
const colorsRequire = createRequire(iconsRequire.resolve('@ant-design/colors'));
const fastRequire = createRequire(colorsRequire.resolve('@ant-design/fast-color'));
const definitions = iconsRequire('@ant-design/icons-svg/lib/index.js');
const icons = {};
for (const [name, def] of Object.entries(definitions)) {
  if (!def.icon) continue;
  const svg = typeof def.icon === 'function' ? def.icon('__primary__', '__secondary__') : def.icon;
  const paths = [];
  function walk(n) {
    if (n.tag === 'path') paths.push(n.attrs);
    for (const child of n.children || []) walk(child);
  }
  walk(svg);
  icons[name] = { viewBox: svg.attrs.viewBox.split(' ').map(Number), paths };
}
const fastColor = (await readFile(fastRequire.resolve('../es/FastColor.js'), 'utf8'))
  .replace('import presetColors from "./presetColors";', `const presetColors = ${JSON.stringify(fastRequire('./presetColors').default)};`)
  .replace('export class FastColor', 'class FastColor');
const generate = (await readFile(colorsRequire.resolve('../es/generate.js'), 'utf8'))
  .replace("import { FastColor } from '@ant-design/fast-color';", '')
  .replace('export default function generate', 'function generate');
const runtime = await readFile(new URL('./templates/Icon.runtime.js', import.meta.url), 'utf8');
const header = `/**\n * @schema 2.18\n * @input name: string = "SearchOutlined"\n * @input fontSize: number = 16\n * @input color: color = #000000E0\n * @input twoToneColor: string = "#1677ff"\n * @input rotate: number = 0\n */\n// Generated by scripts/generate-icon-canvas.mjs from official Ant Design packages.\n// Official SVG definitions and color algorithms are MIT licensed.\n`;
await writeFile(new URL('../canvas-components/Icon.js', import.meta.url), header + fastColor + '\n' + generate + '\nconst icons = ' + JSON.stringify(icons) + ';\n' + runtime);
console.log(`Generated ${Object.keys(icons).length} official icon definitions.`);
